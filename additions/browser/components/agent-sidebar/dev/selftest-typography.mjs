import assert from "node:assert/strict";
import { ConfigStore } from "../modules/ConfigStore.sys.mjs";
import { applySidebarFontScale, normalizeFontScale } from "../modules/SidebarTypography.sys.mjs";
const data = new Map();
const backend = { persistent: true, getString: (key, fallback) => data.get(key) ?? fallback, setString: (key, value) => data.set(key, value) };
const first = new ConfigStore(backend);
assert.equal(first.getSidebarFontScale(), 100);
first.setSidebarFontScale(140);
assert.equal(new ConfigStore(backend).getSidebarFontScale(), 140);
for (const [input, expected] of [[null,100], ["bad",100], [Infinity,100], [20,90], [900,180], [135,140]]) assert.equal(normalizeFontScale(input), expected);
const styles = new Map();
let reads = 0;
const doc = { body: {}, documentElement: { style: { getPropertyValue: key => styles.get(key), setProperty: (key,value) => styles.set(key,value) } }, defaultView: { getComputedStyle: () => { reads++; return {fontSize:"13px"}; } } };
applySidebarFontScale(doc, 180);
assert.equal(styles.get("--frx-base-font-size"), "13px");
assert.equal(styles.get("--frx-font-scale"), "1.8");
applySidebarFontScale(doc, 100);
assert.equal(reads, 1);
assert.equal(styles.get("--frx-font-scale"), "1");
assert.equal(data.size, 1, "typography must not create/change model profiles or keys");
console.log("Sidebar typography: default preservation, bounds, persistence and no cumulative scaling passed");
